/** Перевод по ключу; {0}, {1} — подстановки. */
export function t(key, ...args) {
  const dict = DICTS[lang()];
  let s = key in dict ? dict[key] : (key in RU ? RU[key] : key);
  args.forEach((a, i) => { s = s.split('{' + i + '}').join(String(a)); });
  return s;
}

